"use client";

import { Card, CardHeader, Skeleton } from "@/components/common/Card";
import { Checkbox, Field, Input, Select, Textarea } from "@/components/form/fields";
import Button from "@/components/ui/button/Button";
import { api, ApiError } from "@/lib/api";
import { bookingKeys, type OnlineBookingSettings } from "@/lib/booking";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import Link from "next/link";
import { useState } from "react";
import { Switch } from "./ClinicSection";

const NOTICE = [
  [0, "Sin anticipación"],
  [1, "1 hora antes"],
  [2, "2 horas antes"],
  [4, "4 horas antes"],
  [12, "12 horas antes"],
  [24, "1 día antes"],
  [48, "2 días antes"],
] as const;

/** Configuración → Reserva en línea (docs/reservas.md). */
export default function OnlineBookingSection() {
  const settings = useQuery({ queryKey: bookingKeys.settings, queryFn: () => api<{ data: OnlineBookingSettings }>("online-booking/settings").then((r) => r.data) });
  if (!settings.data) return <Skeleton className="h-96" />;
  return <Editor key={JSON.stringify(settings.data)} initial={settings.data} />;
}

function Editor({ initial }: { initial: OnlineBookingSettings }) {
  const queryClient = useQueryClient();
  const [form, setForm] = useState(initial);
  const [copied, setCopied] = useState(false);
  const save = useMutation({
    mutationFn: (body: OnlineBookingSettings) =>
      api<{ data: OnlineBookingSettings }>("online-booking/settings", {
        method: "PUT",
        body: { enabled: body.enabled, min_notice_hours: body.min_notice_hours, max_days_ahead: body.max_days_ahead, choose_professional: body.choose_professional, message: body.message || null },
      }).then((r) => r.data),
    onSuccess: (d) => queryClient.setQueryData(bookingKeys.settings, d),
  });
  const set = <K extends keyof OnlineBookingSettings>(key: K, value: OnlineBookingSettings[K]) => setForm((f) => ({ ...f, [key]: value }));
  const url = form.public_url;
  const dirty = JSON.stringify(form) !== JSON.stringify(initial);
  const error = save.error as ApiError | null;

  if (!initial.included_in_plan) {
    return (
      <Card>
        <div className="p-6">
          <p className="text-base font-semibold text-gray-800 dark:text-white/90">La reserva en línea está disponible desde el plan Pro</p>
          <p className="mt-1 text-sm text-gray-600 dark:text-gray-300">Tus clientes piden la cita desde un enlace y tú la aceptas o la rechazas.</p>
          <Link href="/app/configuracion?seccion=plan" className="mt-4 inline-flex rounded-lg bg-brand-500 px-4 py-2 text-sm font-medium text-white hover:bg-brand-600">
            Ver planes
          </Link>
        </div>
      </Card>
    );
  }

  return (
    <div className="space-y-6">
      <Card>
        <div className="flex items-start justify-between gap-4 p-5">
          <div>
            <p className="text-base font-semibold text-gray-800 dark:text-white/90">Recibir solicitudes de cita en línea</p>
            <p className="mt-1 text-sm text-gray-600 dark:text-gray-300">
              Las personas eligen servicio, día y hora desde tu enlace. <b>Ninguna cita queda en firme hasta que tu equipo la acepte</b>; mientras tanto, la hora queda apartada.
            </p>
          </div>
          <Switch checked={form.enabled} onChange={(v) => set("enabled", v)} label="Recibir solicitudes en línea" />
        </div>
        {initial.enabled && (
          <div className="border-t border-gray-100 px-5 py-4 dark:border-gray-800">
            <p className="mb-2 text-theme-xs font-semibold text-gray-500">Tu enlace de reservas: compártelo en Instagram, WhatsApp, Google o en un QR en el mostrador.</p>
            <div className="flex flex-wrap items-center gap-2">
              <code className="min-w-0 flex-1 truncate rounded-lg bg-gray-50 px-3 py-2 text-sm text-gray-800 dark:bg-white/5 dark:text-gray-200">{url}</code>
              <Button
                variant="outline"
                size="sm"
                onClick={() => {
                  navigator.clipboard?.writeText(url).then(() => {
                    setCopied(true);
                    setTimeout(() => setCopied(false), 2000);
                  });
                }}
              >
                {copied ? "¡Copiado!" : "Copiar"}
              </Button>
              <a href={form.public_path} target="_blank" rel="noreferrer" className="rounded-lg border border-gray-300 px-3 py-1.5 text-sm font-medium text-gray-700 hover:bg-gray-50 dark:border-gray-700 dark:text-gray-300">
                Abrir
              </a>
            </div>
            <div className="mt-4 flex flex-wrap items-center gap-5 rounded-xl bg-gray-50 p-4 dark:bg-white/5">
              {/* eslint-disable-next-line @next/next/no-img-element -- generated by our API */}
              <img src="/api/backend/online-booking/qr" alt="Código QR de tu página de reservas" className="size-32 rounded-lg bg-white p-1" style={{ imageRendering: "pixelated" }} />
              <div className="min-w-0 flex-1">
                <p className="text-sm font-semibold text-gray-800 dark:text-white/90">Código QR</p>
                <p className="mt-0.5 text-theme-sm text-gray-500">Para el mostrador, la sala de espera o tus redes: quien lo escanee llega directo a pedir su cita.</p>
                <div className="mt-3 flex flex-wrap gap-2">
                  <a href="/imprimir/reservas" target="_blank" rel="noreferrer" className="rounded-lg bg-brand-500 px-3 py-1.5 text-sm font-medium text-white hover:bg-brand-600">
                    Imprimir cartel
                  </a>
                  <a href="/api/backend/online-booking/qr" download="qr-reservas.png" className="rounded-lg border border-gray-300 px-3 py-1.5 text-sm font-medium text-gray-700 hover:bg-gray-50 dark:border-gray-700 dark:text-gray-300">
                    Descargar QR
                  </a>
                </div>
              </div>
            </div>
          </div>
        )}
      </Card>

      <Card>
        <CardHeader title="Reglas" description="Qué horas se ofrecen. Las horas libres salen de los horarios, bloqueos y citas de la agenda." />
        <div className="grid gap-5 p-5 sm:grid-cols-2">
          <Field label="Anticipación mínima" htmlFor="min_notice" hint="No se ofrecen horas más cercanas que esto.">
            <Select id="min_notice" value={form.min_notice_hours} onChange={(e) => set("min_notice_hours", Number(e.target.value))}>
              {NOTICE.map(([v, label]) => (
                <option key={v} value={v}>
                  {label}
                </option>
              ))}
            </Select>
          </Field>
          <Field label="Hasta cuántos días adelante" htmlFor="max_days" hint="Entre 1 y 90 días." error={error?.errors.max_days_ahead?.[0]}>
            <Input id="max_days" type="number" min={1} max={90} value={form.max_days_ahead} onChange={(e) => set("max_days_ahead", Number(e.target.value))} />
          </Field>
          <div className="sm:col-span-2">
            <Checkbox
              checked={form.choose_professional}
              onChange={(e) => set("choose_professional", e.target.checked)}
              label="Dejar elegir el profesional"
              description="Si no, se asigna quien esté libre a esa hora (siempre puedes cambiarlo al aceptar)."
            />
          </div>
          <div className="sm:col-span-2">
            <Field label="Mensaje en la página de reservas" htmlFor="message" optional hint="Por ejemplo: «Para urgencias llama al 607 643 2210»." error={error?.errors.message?.[0]}>
              <Textarea id="message" rows={2} maxLength={300} value={form.message ?? ""} onChange={(e) => set("message", e.target.value)} />
            </Field>
          </div>
          <p className="text-theme-sm text-gray-600 sm:col-span-2 dark:text-gray-300">
            Los servicios que aparecen son los marcados con «Los tutores pueden pedirlo en línea» en{" "}
            <Link href="/app/configuracion?seccion=servicios" className="font-medium text-brand-600 underline">
              Servicios
            </Link>
            .
          </p>
        </div>
      </Card>

      <div className="flex items-center justify-end gap-3">
        {save.isSuccess && !dirty && <span className="text-theme-sm text-success-600">Guardado</span>}
        {error && !error.errors && <span className="text-theme-sm text-error-600">{error.message}</span>}
        <Button variant="outline" disabled={!dirty} onClick={() => setForm(initial)}>
          Descartar
        </Button>
        <Button disabled={!dirty} loading={save.isPending} onClick={() => save.mutate(form)}>
          Guardar
        </Button>
      </div>
    </div>
  );
}
